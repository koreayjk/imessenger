--  자기 메시지만, 그리고 관리자가 가린 메시지는 손대지 못합니다.
--  이 파일은 칸 하나만 더합니다.
--
--  Supabase → SQL Editor 에 붙여넣고 실행하세요. (재실행해도 안전)
